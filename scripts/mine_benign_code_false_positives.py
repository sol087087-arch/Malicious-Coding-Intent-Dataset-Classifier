#!/usr/bin/env python3
"""Mine curated benign-code false positives from a hard-negative hold-out."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter
from pathlib import Path

import numpy as np

os.environ.setdefault("HF_HUB_OFFLINE", "1")
os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from build_benign_code_holdout import is_quality_code_block, norm_hash  # noqa: E402
from evaluate_benign_code_holdout import load_jsonl, score_texts  # noqa: E402
from evaluate_classifier import load_binary_threshold  # noqa: E402
from plot_score_dist import load_encoder  # noqa: E402


def is_curated_candidate(text: str, path: str | None, source: str) -> tuple[bool, str | None]:
    if not is_quality_code_block(text, min_chars=220, max_chars=3500):
        return False, "base_quality"

    lowered = text.lower()
    path_low = (path or "").lower()
    source_low = source.lower()
    lines = [ln for ln in text.splitlines() if ln.strip()]
    avg_line = sum(len(ln) for ln in lines) / max(1, len(lines))

    reject_markers = [
        ".min.js",
        "biglime-min",
        "node_modules",
        "vendor",
        "sysroots",
        "/usr/lib/python",
        "\\usr\\lib\\python",
        "/lib/python/",
        "\\lib\\python\\",
        "/encodings/",
        "\\encodings\\",
        "site-packages",
        "dist-packages",
        "libs_arm",
        "third_party",
        "generated by",
        "auto-generated",
        "autogenerated",
        "swigregister",
        "_swig_",
        "base64",
        "data:image",
        "redteam",
        "red_team",
        "malware",
        "vxunderground",
        "exploit",
    ]
    if any(marker in path_low or marker in lowered for marker in reject_markers):
        return False, "marker"

    compact_lines = sum(1 for ln in lines if len(ln) > 220)
    if compact_lines / max(1, len(lines)) > 0.15:
        return False, "long_lines"
    if avg_line > 145:
        return False, "avg_line"
    comment_lines = sum(1 for ln in lines if ln.lstrip().startswith(("#", "//", "/*", "*")))
    if comment_lines / max(1, len(lines)) > 0.55:
        return False, "comment_heavy"

    alpha = sum(ch.isalpha() for ch in text) / max(1, len(text))
    digits = sum(ch.isdigit() for ch in text) / max(1, len(text))
    braces = sum(ch in "{}[]();,:" for ch in text) / max(1, len(text))
    if alpha < 0.22:
        return False, "low_alpha"
    if digits > 0.24:
        return False, "high_digits"
    if braces > 0.38 and "local_repo_vesuvius" in source_low:
        return False, "dense_vesuvius"

    return True, None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-dir", type=Path, required=True)
    ap.add_argument("--holdout", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--report", type=Path, default=None)
    ap.add_argument("--device", choices=["auto", "cuda", "cpu"], default="auto")
    ap.add_argument("--batch-size", type=int, default=32)
    ap.add_argument("--max-length", type=int, default=128)
    ap.add_argument("--profile", default=None)
    ap.add_argument("--threshold", type=float, default=None)
    ap.add_argument("--max-total", type=int, default=800)
    ap.add_argument("--max-per-source", type=int, default=160)
    ap.add_argument("--min-score", type=float, default=None)
    args = ap.parse_args()

    import joblib

    rows = load_jsonl(args.holdout)
    texts = [row["text"] for row in rows]
    clf_bin = joblib.load(args.model_dir / "clf_binary.joblib")
    model = load_encoder("BAAI/bge-m3", args.device, args.max_length)
    threshold = args.threshold
    if threshold is None:
        threshold = load_binary_threshold(args.model_dir, profile=args.profile)
    if args.min_score is not None:
        threshold = max(threshold, args.min_score)

    scores = score_texts(texts, clf_bin, model, args.batch_size)
    candidates: list[tuple[float, dict]] = []
    rejected = Counter()
    flagged_by_source = Counter()

    for row, score in zip(rows, scores):
        score = float(score)
        if score < threshold:
            continue
        source = row.get("source", "unknown")
        flagged_by_source[source] += 1
        ok, reason = is_curated_candidate(row["text"], row.get("path"), source)
        if not ok:
            rejected[reason or "unknown"] += 1
            continue
        candidates.append((score, row))

    candidates.sort(key=lambda item: item[0], reverse=True)
    kept: list[dict] = []
    seen: set[str] = set()
    kept_by_source = Counter()
    for score, row in candidates:
        source = row.get("source", "unknown")
        if kept_by_source[source] >= args.max_per_source:
            continue
        h = norm_hash(row["text"])
        if h in seen:
            continue
        seen.add(h)
        out_row = dict(row)
        out_row["source"] = f"{source}_fp_mined"
        out_row["mined_from"] = source
        out_row["mined_score"] = round(score, 6)
        out_row["malicious"] = 0
        out_row["categories"] = []
        kept.append(out_row)
        kept_by_source[source] += 1
        if len(kept) >= args.max_total:
            break

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as f:
        for row in kept:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    report = {
        "model_dir": str(args.model_dir),
        "holdout": str(args.holdout),
        "out": str(args.out),
        "threshold": round(float(threshold), 6),
        "flagged_total": int(sum(flagged_by_source.values())),
        "candidate_total": len(candidates),
        "kept_total": len(kept),
        "flagged_by_source": dict(sorted(flagged_by_source.items())),
        "kept_by_source": dict(sorted(kept_by_source.items())),
        "rejected": dict(sorted(rejected.items())),
    }
    report_path = args.report or args.out.with_suffix(".report.json")
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(report, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
