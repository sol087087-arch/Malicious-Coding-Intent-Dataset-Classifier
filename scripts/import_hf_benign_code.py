#!/usr/bin/env python3
"""Stream benign OSS-code samples from Hugging Face.

This intentionally samples from large code corpora via datasets streaming
instead of downloading full shards. The output is a JSONL hold-out/pool source
for benign-code hard-negative evaluation.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import subprocess
import sys
import time
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlencode

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from build_benign_code_holdout import clean_text, is_quality_code_block, norm_hash  # noqa: E402


DEFAULT_OUT = ROOT / "data" / "external" / "hf_benign_code_sample.jsonl"
DEFAULT_DATASETS = [
    "codeparrot/codeparrot-clean-train:default:train",
    "codeparrot/codeparrot-clean-valid:default:train",
]
CODE_KEYS = ("code", "content", "text", "func_code", "body")
PATH_KEYS = ("path", "file_path", "filepath", "filename", "file_name")
LANG_KEYS = ("language", "lang", "programming_language")
REPO_KEYS = ("repo_name", "repository_name", "repo", "repository", "project")
LICENSE_KEYS = ("license", "licenses")


@dataclass(frozen=True)
class DatasetSpec:
    repo: str
    config: str | None
    split: str

    @property
    def source(self) -> str:
        parts = [self.repo]
        if self.config:
            parts.append(self.config)
        parts.append(self.split)
        return "hf_benign_code:" + ":".join(parts)


def parse_spec(raw: str) -> DatasetSpec:
    parts = raw.split(":")
    if len(parts) == 1:
        return DatasetSpec(parts[0], None, "train")
    if len(parts) == 2:
        return DatasetSpec(parts[0], parts[1] or None, "train")
    return DatasetSpec(parts[0], parts[1] or None, ":".join(parts[2:]) or "train")


def row_value(row: dict[str, Any], keys: tuple[str, ...]) -> Any:
    for key in keys:
        if key in row and row[key] not in (None, ""):
            return row[key]
    return None


def sliding_blocks(text: str, min_chars: int, max_chars: int, step_chars: int) -> list[str]:
    text = clean_text(text)
    if len(text) < min_chars:
        return []
    if len(text) <= max_chars:
        return [text]
    blocks: list[str] = []
    for start in range(0, len(text), step_chars):
        part = text[start : start + max_chars].strip()
        if len(part) >= min_chars:
            blocks.append(part)
    return blocks


def is_probably_benign_code(text: str, path: str, language: str) -> tuple[bool, str | None]:
    if not is_quality_code_block(text, min_chars=220, max_chars=4000):
        return False, "base_quality"

    lowered = text.lower()
    path_low = path.lower()
    lang_low = language.lower()
    reject_markers = [
        ".min.js",
        "node_modules",
        "vendor/",
        "\\vendor\\",
        "sysroots/",
        "\\sysroots\\",
        "/usr/lib/python",
        "\\usr\\lib\\python",
        "/lib/python/",
        "\\lib\\python\\",
        "/encodings/",
        "\\encodings\\",
        "site-packages",
        "dist-packages",
        "libs_arm/",
        "\\libs_arm\\",
        "third_party",
        "generated by",
        "auto-generated",
        "autogenerated",
        "swigregister",
        "_swig_",
        ".this.own",
        "base64",
        "data:image",
        "malware",
        "ransomware",
        "keylogger",
        "shellcode",
        "metasploit",
        "exploit",
        "cve-",
        "payload",
        "backdoor",
        "botnet",
        "vxunderground",
    ]
    if any(marker in path_low or marker in lowered for marker in reject_markers):
        return False, "marker"

    lines = [ln for ln in text.splitlines() if ln.strip()]
    if not lines:
        return False, "empty"
    avg_line = sum(len(ln) for ln in lines) / len(lines)
    if avg_line > 150:
        return False, "avg_line"
    if sum(1 for ln in lines if len(ln) > 220) / len(lines) > 0.12:
        return False, "long_lines"

    if lang_low in {"json", "yaml", "markdown", "text"}:
        return False, "not_code_lang"
    return True, None


def record_from_block(
    block: str,
    spec: DatasetSpec,
    row: dict[str, Any],
    path: str,
    language: str,
    score_index: int,
) -> dict[str, Any]:
    repo_name = row_value(row, REPO_KEYS)
    license_value = row_value(row, LICENSE_KEYS)
    return {
        "text": block,
        "malicious": 0,
        "categories": [],
        "source": spec.source,
        "language": language or spec.config or "code",
        "path": path,
        "repo_name": repo_name,
        "license": license_value,
        "hf_row_index": score_index,
    }


def fetch_rows_api(
    spec: DatasetSpec,
    offset: int,
    length: int,
    insecure: bool,
    retries: int,
    retry_sleep: float,
) -> dict[str, Any]:
    query = urlencode(
        {
            "dataset": spec.repo,
            "config": spec.config or "default",
            "split": spec.split,
            "offset": offset,
            "length": length,
        }
    )
    cmd = ["curl.exe", "-fsSL", f"https://datasets-server.huggingface.co/rows?{query}"]
    if insecure:
        cmd.insert(1, "-k")
    last_error = ""
    for attempt in range(retries + 1):
        proc = subprocess.run(cmd, text=True, encoding="utf-8", capture_output=True)
        if proc.returncode == 0:
            return json.loads(proc.stdout)
        last_error = (proc.stderr or proc.stdout or "").strip()
        if attempt < retries:
            time.sleep(retry_sleep * (attempt + 1))
    raise RuntimeError(last_error or f"curl failed with exit code {proc.returncode}")


def iter_rows_api(
    spec: DatasetSpec,
    page_size: int,
    max_scan: int,
    seed: int,
    insecure: bool,
    request_sleep: float,
    retries: int,
    retry_sleep: float,
) -> tuple[Any, int | None]:
    first = fetch_rows_api(spec, 0, min(page_size, 100), insecure, retries, retry_sleep)
    total = first.get("num_rows_total")
    if not isinstance(total, int) or total <= 0:
        total = None

    offsets: list[int]
    if total:
        max_offset = max(0, total - 1)
        max_pages = max(1, min((max_scan + page_size - 1) // page_size, (total + page_size - 1) // page_size))
        rng = random.Random(seed + hash(spec.source) % 100_000)
        offsets = sorted({rng.randrange(0, max_offset + 1) // page_size * page_size for _ in range(max_pages * 2)})
        offsets = offsets[:max_pages]
        if 0 not in offsets:
            offsets.insert(0, 0)
    else:
        offsets = list(range(0, max_scan, page_size))

    def rows() -> Any:
        local_offsets = list(offsets)
        if local_offsets and local_offsets[0] == 0:
            for item in first.get("rows", []):
                row = item.get("row")
                if isinstance(row, dict):
                    yield row
            local_offsets = local_offsets[1:]
        for offset in local_offsets:
            if request_sleep > 0:
                time.sleep(request_sleep)
            page = fetch_rows_api(spec, offset, min(page_size, 100), insecure, retries, retry_sleep)
            for item in page.get("rows", []):
                row = item.get("row")
                if isinstance(row, dict):
                    yield row

    return rows(), total


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--dataset", action="append", default=[], help="repo[:config[:split]], repeatable")
    ap.add_argument("--backend", choices=["rows-api", "datasets"], default="rows-api")
    ap.add_argument("--target", type=int, default=50_000)
    ap.add_argument("--max-per-dataset", type=int, default=12_000)
    ap.add_argument("--max-scan-per-dataset", type=int, default=250_000)
    ap.add_argument("--page-size", type=int, default=100)
    ap.add_argument("--shuffle-buffer", type=int, default=10_000)
    ap.add_argument("--seed", type=int, default=13)
    ap.add_argument("--min-chars", type=int, default=220)
    ap.add_argument("--max-chars", type=int, default=4000)
    ap.add_argument("--step-chars", type=int, default=1800)
    ap.add_argument("--trust-remote-code", action="store_true")
    ap.add_argument("--keep-cache", action="store_true")
    ap.add_argument("--insecure", action="store_true", default=True)
    ap.add_argument("--request-sleep", type=float, default=0.5)
    ap.add_argument("--retries", type=int, default=6)
    ap.add_argument("--retry-sleep", type=float, default=20.0)
    args = ap.parse_args()

    if not args.keep_cache:
        os.environ.setdefault("HF_DATASETS_CACHE", str(ROOT / "data" / "external" / ".hf_datasets_cache"))

    if args.backend == "datasets":
        from datasets import load_dataset
    else:
        load_dataset = None

    specs = [parse_spec(raw) for raw in (args.dataset or DEFAULT_DATASETS)]
    random.Random(args.seed).shuffle(specs)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    seen: set[str] = set()
    total = 0
    by_source: Counter[str] = Counter()
    rejected: Counter[str] = Counter()
    scanned: Counter[str] = Counter()
    totals: dict[str, int] = {}
    errors: dict[str, str] = {}

    with args.out.open("w", encoding="utf-8") as f:
        for spec in specs:
            if total >= args.target:
                break
            try:
                if args.backend == "rows-api":
                    ds, num_rows_total = iter_rows_api(
                        spec,
                        min(args.page_size, 100),
                        args.max_scan_per_dataset,
                        args.seed,
                        args.insecure,
                        args.request_sleep,
                        args.retries,
                        args.retry_sleep,
                    )
                    if num_rows_total is not None:
                        totals[spec.source] = num_rows_total
                else:
                    assert load_dataset is not None
                    if spec.config:
                        ds = load_dataset(
                            spec.repo,
                            spec.config,
                            split=spec.split,
                            streaming=True,
                            trust_remote_code=args.trust_remote_code,
                        )
                    else:
                        ds = load_dataset(
                            spec.repo,
                            split=spec.split,
                            streaming=True,
                            trust_remote_code=args.trust_remote_code,
                        )
                    if args.shuffle_buffer > 0:
                        ds = ds.shuffle(seed=args.seed, buffer_size=args.shuffle_buffer)
            except Exception as exc:  # noqa: BLE001
                errors[spec.source] = repr(exc)
                continue

            source_added = 0
            for idx, row in enumerate(ds):
                scanned[spec.source] += 1
                if idx >= args.max_scan_per_dataset:
                    break
                if total >= args.target or source_added >= args.max_per_dataset:
                    break
                if not isinstance(row, dict):
                    rejected["row_type"] += 1
                    continue

                raw_text = row_value(row, CODE_KEYS)
                if not isinstance(raw_text, str):
                    rejected["missing_code"] += 1
                    continue
                path = str(row_value(row, PATH_KEYS) or "")
                language = str(row_value(row, LANG_KEYS) or spec.config or "code")

                for block in sliding_blocks(raw_text, args.min_chars, args.max_chars, args.step_chars):
                    ok, reason = is_probably_benign_code(block, path, language)
                    if not ok:
                        rejected[reason or "unknown"] += 1
                        continue
                    h = norm_hash(block)
                    if h in seen:
                        rejected["duplicate"] += 1
                        continue
                    seen.add(h)
                    rec = record_from_block(block, spec, row, path, language, idx)
                    f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    total += 1
                    source_added += 1
                    by_source[spec.source] += 1
                    if total >= args.target or source_added >= args.max_per_dataset:
                        break

    report = {
        "out": str(args.out),
        "target": args.target,
        "total": total,
        "datasets": [spec.source for spec in specs],
        "by_source": dict(sorted(by_source.items())),
        "scanned": dict(sorted(scanned.items())),
        "num_rows_total": totals,
        "rejected": dict(sorted(rejected.items())),
        "errors": errors,
    }
    report_path = args.out.with_suffix(".report.json")
    report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(report, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
